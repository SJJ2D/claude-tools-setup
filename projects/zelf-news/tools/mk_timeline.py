"""mk_timeline.py — script.json (+ optional audio/lines_meta.json, audio/env.json) → timeline.js, audio/placement.json
Line start = previous line end + its scripted pause_after (first line starts at lead_in). Line length = the real take
length when audio/lines_meta.json has it ({id: {dur, words: [[t_rel, 'word'], ...]}}), else the script estimate with
words spread by length. Scene cuts are anchors on lines, so a re-recorded voice re-flows the whole film.
python3 tools/mk_timeline.py            (run from the project root)"""
import json, os, sys
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
S = json.load(open(os.path.join(R, 'script.json'), encoding='utf-8'))
mp = os.path.join(R, 'audio', 'lines_meta.json'); META = json.load(open(mp, encoding='utf-8')) if os.path.exists(mp) else {}
ep = os.path.join(R, 'audio', 'env.json'); ENV = json.load(open(ep)) if os.path.exists(ep) else None

import difflib, re as _re
def tokens(text):
    for ch in '…،.؟!«»:': text = text.replace(ch, ' ')
    return text.split()
def norm(w): return _re.sub('[\u064B-\u0652\u0670\u0640]', '', w).replace('أ', 'ا').replace('إ', 'ا').replace('آ', 'ا').replace('ة', 'ه').replace('ى', 'ي').replace('ؤ', 'و').replace('ئ', 'ي')
def align(script_words, heard, t0, dur):
    """times of the heard words (ASR spelling) mapped onto the script's own words, in order"""
    a = [norm(w) for w in script_words]; b = [norm(_re.sub('[^\u0621-\u064A0-9]', '', h[1])) for h in heard]
    times = [None] * len(a)
    for blk in difflib.SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks():
        for k in range(blk.size): times[blk.a + k] = heard[blk.b + k][0]
    if all(x is None for x in times):                              # nothing matched: spread by position
        times = [heard[min(len(heard) - 1, round(i * (len(heard) - 1) / max(1, len(a) - 1)))][0] for i in range(len(a))]
    for i in range(len(a)):                                          # fill gaps between known neighbours
        if times[i] is None:
            lo = next((j for j in range(i - 1, -1, -1) if times[j] is not None), None)
            hi = next((j for j in range(i + 1, len(a)) if times[j] is not None), None)
            tl = times[lo] if lo is not None else 0.0; th = times[hi] if hi is not None else dur
            il = lo if lo is not None else -1; ih = hi if hi is not None else len(a)
            times[i] = tl + (th - tl) * (i - il) / (ih - il)
    for i in range(1, len(a)): times[i] = max(times[i], times[i - 1])
    return [[round(t0 + x, 3), w] for x, w in zip(times, script_words)]
t = float(S.get('lead_in', 1.5)); lines, words, place = {}, {}, {}
for ln in S['lines']:
    m = META.get(ln['id'])
    dur = float(m['dur']) if m else float(ln['est'])
    lines[ln['id']] = [round(t, 3), round(t + dur, 3)]; place[ln['id']] = round(t, 3)
    if m and m.get('words'):
        words[ln['id']] = align(tokens(ln['text']), m['words'], t, dur)
    else:
        ws = tokens(ln['text'])
        tot = sum(len(w) + 1.5 for w in ws) or 1; acc = 0; out = []
        for w in ws:
            out.append([round(t + dur * acc / tot, 3), w]); acc += len(w) + 1.5
        words[ln['id']] = out
    t += dur + float(ln.get('pause_after', 0.3))
dur_total = round(t - float(S['lines'][-1].get('pause_after', 0.3)) + float(S.get('tail', 2.0)), 3)

def resolve(a):
    kind = a[0]
    if kind == 'start': return 0.0
    if kind == 'line_start': return lines[a[1]][0] + (a[2] if len(a) > 2 else 0)
    if kind == 'line_end': return lines[a[1]][1] + (a[2] if len(a) > 2 else 0)
    if kind == 'word':                                            # ['word', 'l3', 'fragment', offset]
        hit = next((w for w in words[a[1]] if a[2] in w[1]), None)
        return (hit[0] if hit else lines[a[1]][0]) + (a[3] if len(a) > 3 else 0)
    raise SystemExit('bad anchor ' + str(a))
starts = [(c['id'], round(resolve(c['at']), 3)) for c in S['cuts']]
cuts = {cid: [st, (starts[i + 1][1] if i + 1 < len(starts) else dur_total)] for i, (cid, st) in enumerate(starts)}
for cid, (a, b) in cuts.items():
    if b <= a: raise SystemExit(f'cut {cid} has no length: {a}..{b}')
TL = {'dur': dur_total, 'cuts': cuts, 'lines': lines, 'words': words, 'env': ENV['env'] if ENV else None, 'envRate': ENV['rate'] if ENV else 30,
      'real_voice': bool(META)}
open(os.path.join(R, 'timeline.js'), 'w', encoding='utf-8').write('// generated by tools/mk_timeline.py — do not edit\nwindow.ZN_TL = ' + json.dumps(TL, ensure_ascii=False) + ';\n')
os.makedirs(os.path.join(R, 'audio'), exist_ok=True)
json.dump({'dur': dur_total, 'place': place, 'lines': lines, 'cuts': cuts}, open(os.path.join(R, 'audio', 'placement.json'), 'w'), ensure_ascii=False, indent=1)
open(os.path.join(R, 'script.js'), 'w', encoding='utf-8').write('// generated from script.json by tools/mk_timeline.py — do not edit\nwindow.ZN_SCRIPT = ' + json.dumps(S, ensure_ascii=False) + ';\n')
print(f'dur {dur_total}s  ({"real takes" if META else "ESTIMATED"})')
for cid, (a, b) in cuts.items(): print(f'  {cid:4s} {a:6.2f} → {b:6.2f}  ({b - a:.2f}s)')
for ln in S['lines']: print(f"  {ln['id']:4s} {lines[ln['id']][0]:6.2f}–{lines[ln['id']][1]:6.2f}  {ln['text']}")
